"""License gate (PLAN-VISUALS.md decision V5): every third-party asset must be
free to use commercially, with no fee or royalty.

Walks every content_src/**/manifest.json (via build_credits.walk_manifest, so
both manifest schemas are handled the same way the credits screen reads them)
and data/cars/*/LICENSE.txt, and fails on any entry that:
  - has no source, or
  - has a license that isn't CC0 / public domain / CC-BY 4.0 / the
    Copernicus Sentinel data terms / our own original (procedural or
    generated) work, or
  - names a disallowed term (NC, ND, SA, personal/editorial use, a store
    license such as Fab/Megascans, royalties).
CC-BY needs no separate credit check: build_credits.py prints every manifest
entry, so a CC-BY entry that passes here is credited automatically.

Usage:  python pipeline/verify_asset_licenses.py      (exit 1 on any failure)
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_credits import CARS_DIR, CONTENT_SRC, EXCLUDE_MANIFESTS, walk_manifest

# Checked first: any hit fails the entry, even if an allowed term also appears.
DENY = [
    (r"\bnc\b|non-?commercial", "non-commercial"),
    (r"\bnd\b|no-?deriv", "no-derivatives"),
    (r"\bsa\b|share-?alike", "share-alike"),
    (r"personal use|editorial", "personal/editorial use only"),
    (r"royalt", "royalty"),
    (r"\bfab\b|megascans|quixel|standard license|marketplace|turbosquid|sketchfab store", "store license"),
]
ALLOW = [
    r"\bcc0\b|creative commons 0|cc zero",
    r"public domain",
    r"\bcc[- ]by[- ]4\.0\b|\bcc by 4\.0\b",
    r"original work|original procedural|procedural|generated by this repo",
    # free, full and open; commercial use allowed with attribution (Track L)
    r"copernicus sentinel data terms",
]


def check_license(text):
    """Returns None if `text` is an allowed license, else the reason it fails."""
    t = text.lower()
    for pat, why in DENY:
        if re.search(pat, t):
            return why
    if any(re.search(p, t) for p in ALLOW):
        return None
    return "unrecognized license"


def entries():
    """Yields (where, name, source, license) for every asset record."""
    for m in sorted(CONTENT_SRC.glob("**/manifest.json")):
        if m.name in EXCLUDE_MANIFESTS:
            continue
        for name, _author, source, license_ in walk_manifest(m):
            yield m.relative_to(CONTENT_SRC.parent).as_posix(), name, source, license_
    for lp in sorted(CARS_DIR.glob("*/LICENSE.txt")):
        text = lp.read_text(encoding="utf-8").strip()
        yield lp.relative_to(CARS_DIR.parent.parent).as_posix(), lp.parent.name, "generated", text


def main():
    failures = []
    n = 0
    for where, name, source, license_ in entries():
        n += 1
        if not source or source == "—":
            failures.append(f"{where}: {name}: no source")
        why = check_license(license_)
        if why:
            failures.append(f"{where}: {name}: {why} ({license_!r})")
    for f in failures:
        print("FAIL", f)
    print(f"{n} asset record(s), {len(failures)} failure(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
